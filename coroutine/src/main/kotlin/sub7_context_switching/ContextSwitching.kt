package sub7_context_switching

/**
 * process context switching
 *      프로세스는 각각 독립된 메모리 영역을 가지고 있기 때문에
 *      A 프로세스에서 B 프로세스로 실행이 변경되면
 *          주소 공간(가상 메모리), 힙, 스택, 레지스터 등 모든 실행 문맥이 교체된다.
 *
 *      → 비용이 가장 큼 (OS 레벨 switching)
 *
 * thread context switching
 *      스레드는 같은 프로세스 내에서 힙 영역을 공유하고, 각각 독립적인 스택 영역을 가진다.
 *
 *      A 스레드에서 B 스레드로 실행이 변경되면:
 *          - 현재 스레드의 레지스터 상태 저장
 *          - 스택 포인터 변경 (다른 스레드의 스택으로 전환)
 *          - 프로그램 카운터 변경
 *
 *      메모리 관점:
 *          - 힙은 그대로 유지 (공유)
 *          - 스택은 완전히 다른 영역으로 교체됨
 *
 *      → OS 스케줄러 개입 필요
 *      → 캐시 locality 깨질 수 있음
 *      → 프로세스보다 가볍지만 여전히 비용 큼
 *
 * coroutine context switching
 *      코루틴은 스레드 위에서 동작하는 유저 레벨 실행 단위이다.
 *
 *      suspend 시:
 *          - 현재 실행 상태를 Continuation 객체(힙 영역)에 저장
 *              - 지역 변수
 *              - 다음 실행 위치 (state machine)
 *              - 필요한 context
 *
 *      resume 시:
 *          - 저장된 상태를 기반으로 이어서 실행
 *
 *      메모리 관점
 *          스레드 변경 없는 경우 (OS 개입 없음):
 *              - 스택을 교체하지 않음
 *              - 필요한 상태만 힙에 저장
 *              - 스레드 스택 전환이 없음
 *
 *          스레드 변경이 발생하는 경우 (OS 스케줄링 비용 발생):
 *              - Dispatcher 에 따라 resume 시 다른 스레드에서 실행될 수 있음
 *              - 이 경우:
 *                  → 새로운 스레드의 스택 위에서 실행됨
 *                  → 기존 상태는 힙(Continuation)에 저장되어 있으므로 문제 없음
 *                  → 스레드 전환 시 OS 스케줄링 비용은 발생할 수 있음
 *
 *      즉,
 *          - 스택 기반 전환이 아니라 상태 기반 전환
 *          - 스레드에 종속되지 않음
 *
 *      비용이 낮은 이유:
 *          - 코루틴 전환 자체는 OS 스케줄러 개입 없이 수행됨
 *          - 스택 전체를 교체하지 않음 (같은 스레드 기준)
 *          - 필요한 상태만 힙에 저장/복원
 *          - 매우 작은 단위로 전환 가능
 *
 *      → 적은 수의 스레드로 많은 작업을 효율적으로 처리할 수 있는 구조
 *          하나의 코어 하나의 스레드 환경이지만, 위에 여러 코루틴이 있으면 동시성(Concurrent)이 확보된다...
 */
