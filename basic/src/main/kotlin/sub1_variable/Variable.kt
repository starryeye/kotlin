package sub1_variable

/**
 * 코틀린의 변수에 대해서 알아본다.
 *
 * Kotlin에서는 변수를 클래스나 함수 내부뿐만 아니라 top-level에도 선언할 수 있다.
 * 변수 선언 시 타입을 명시할 수 있으며, 초기값이 있으면 타입 추론이 가능하다.
 * 초기화되지 않은 변수는 사용이 불가능하며, 지연 초기화 시 타입 선언이 필수이다.
 * val은 불변 변수로 한 번 초기화하면 재할당이 불가능하다.
 * var는 가변 변수로 재할당이 가능하다.
 * Kotlin은 기본적으로 모든 타입을 참조 타입으로 다루며, boxing / unboxing은 컴파일러가 자동으로 처리한다.
 *
 * 참고
 * 기본적으로 val 을 사용하고 값이 변경되어야 할때 var 로 사용
 */

var x = 5 // top 레벨에 위치한 변수이다. 코틀린에서는 변수를 클래스, 함수 외부에 위치 시킬 수 있다.

fun main() {

    val a : Int = 1 // 변수명, 타입, 값

    val b = 1 // 선언과 동시에 초기화를 할 때는 타입을 생략 가능하다. (컴파일러가 타입 추론을 할 수 있다.)

    //-----------------------------------------------------------------

    // 코틀린에서는 초기값이 없는데 사용하면 컴파일 에러이다.
    var number1: Int
    val number2: Int

//    println(number1) // compile error
//    println(number2) // compile error

    //-----------------------------------------------------------------

    // 지연 할당
    val c : Int
    c = 3

    // 지연 할당에서는 타입 추론이 불가능하여 타입을 반드시 선언해줘야한다.
//    val d //compile error
//    d = 123

    //-----------------------------------------------------------------

    /**
     * 변수 선언 키워드 2가지
     * 1. val (value)
     * java 의 final 키워드와 같이 변수에 한번 값을 초기화 하면 재할당 불가능
     *
     * 2. var (variable)
     * 가변 변수로 재할당 가능하다.
     */
    var e : String = "Hello"
    e = "World" //val 이면 compile error

    var f = 123
//    f = "hi" // 한번 타입이 정해지면 타입이 변경되지 않는다. compile error

    //-----------------------------------------------------------------

    // 탑레벨에 위치한 변수를 사용
    x += 1
    println(x)


    //-----------------------------------------------------------------

    // primitive type 은 없다고 생각하자. 모두 reference type 사용
    // unboxing / boxing 에 대해서 개발자는 생각할 필요가 없음. 컴파일러가 알아서 최적화 한다.


    //-----------------------------------------------------------------
}